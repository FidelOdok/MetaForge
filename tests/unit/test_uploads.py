class TestRoutes:
    def test_the_dashboard_can_import_in_one_step(self, client: TestClient) -> None:
        resp = client.post(
            "/v1/uploads",
            files=[("files", ("ref.png", _png(3, 3))), ("files", ("cube.gcode", GCODE))],
            data={"project_id": PROJECT, "approve": "true"},
            headers={"X-MetaForge-Surface": "dashboard"},
        )
        assert resp.status_code == 201, resp.text
        body = resp.json()
        assert body["status"] == "approved" and body["source"] == "dashboard"
        assert all(f["work_product_id"] for f in body["files"])

    def test_an_agent_cannot_approve_its_own_upload(self, client: TestClient) -> None:
        resp = client.post(
            "/v1/uploads",
            files=[("files", ("a.md", b"# a"))],
            data={"approve": "true"},
            headers={"X-MetaForge-Surface": "agent"},
        )
        assert resp.status_code == 403

    def test_a_staged_file_is_served_for_review_but_never_as_active_content(
        self, client: TestClient
    ) -> None:
        resp = client.post(
            "/v1/uploads",
            files=[
                ("files", ("logo.svg", b"<svg onload='alert(1)'/>")),
                ("files", ("r.png", _png(2, 2))),
            ],
        )
        upload = resp.json()
        svg = client.get(f"/v1/uploads/{upload['id']}/files/logo.svg")
        assert svg.status_code == 200
        assert svg.headers["content-type"] == "application/octet-stream"
        assert svg.headers["content-disposition"].startswith("attachment")
        assert "sandbox" in svg.headers["content-security-policy"]
        png = client.get(f"/v1/uploads/{upload['id']}/files/r.png")
        assert png.headers["content-type"] == "image/png"

    def test_an_upload_is_an_approval_a_person_decides(
        self, client: TestClient, twin: InMemoryTwinAPI
    ) -> None:
        upload = client.post("/v1/uploads", files=[("files", ("a.step", b"ISO-10303-21;"))]).json()
        item_id = f"upload:{upload['id']}"
        listed = client.get("/v1/approvals").json()["items"]
        item = next(i for i in listed if i["id"] == item_id)
        assert item["kind"] == "upload" and item["status"] == "pending"
        assert item["allowed_decisions"] == ["approve", "reject"]
        assert item["detail"]["files"][0]["preview_url"].endswith("/files/a.step")

        decided = client.post(
            f"/v1/approvals/{item_id}/decision",
            json={"decision": "approve"},
            headers={"X-MetaForge-Surface": "dashboard"},
        )
        assert decided.status_code == 200, decided.text
        assert decided.json()["status"] == "approved"
        wp_id = client.get(f"/v1/uploads/{upload['id']}").json()["files"][0]["work_product_id"]
        assert wp_id

    def test_an_agent_cannot_decide_an_upload(self, client: TestClient) -> None:
        upload = client.post("/v1/uploads", files=[("files", ("a.md", b"# a"))]).json()
        resp = client.post(
            f"/v1/approvals/upload:{upload['id']}/decision",
            json={"decision": "approve"},
            headers={"X-MetaForge-Surface": "agent", "X-MetaForge-On-Behalf-Of": "someone"},
        )
        assert resp.status_code == 403
