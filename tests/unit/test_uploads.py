class TestFormats:
    def test_images_and_gcode_have_their_own_types(self) -> None:
        assert infer_wp_type(".png") is WorkProductType.IMAGE
        assert infer_wp_type(".jpeg") is WorkProductType.IMAGE
        assert infer_wp_type(".gcode") is WorkProductType.GCODE
        assert infer_wp_type(".bgcode") is WorkProductType.GCODE

    def test_image_size_reads_png_gif_and_jpeg_headers(self) -> None:
        assert image_size(_png(37, 21)) == (37, 21)
        assert image_size(b"GIF89a" + struct.pack("<HH", 640, 480) + b"\x00" * 8) == (640, 480)
        jpeg = (
            b"\xff\xd8\xff\xe0"
            + struct.pack(">H", 16)
            + b"JFIF\x00"
            + b"\x00" * 9
            + b"\xff\xc0"
            + struct.pack(">HBHH", 17, 8, 300, 400)
            + b"\x00" * 12
        )
        assert image_size(jpeg) == (400, 300)

    def test_image_size_is_none_for_anything_else(self) -> None:
        assert image_size(b"<svg/>") is None
        assert image_size(b"\x89PNG") is None


