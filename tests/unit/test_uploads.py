class TestOpenUploads:
    def test_a_link_session_takes_files_until_it_closes(self, store: SqliteUploadStore) -> None:
        upload = service.open_upload(store, project_id=PROJECT, source="link")
        upload = service.add_files(store, upload, [("a.step", b"ISO-10303-21;")])
        upload = service.add_files(store, upload, [("b.png", _png(2, 2))])
        upload = service.close_upload(store, upload)
        assert upload.status == "pending" and len(upload.accepted) == 2
        with pytest.raises(service.UploadError):
            service.add_files(store, upload, [("c.md", b"x")])

    def test_an_open_upload_past_its_time_expires(self, store: SqliteUploadStore) -> None:
        upload = service.open_upload(
            store, project_id=None, source="link", expires_in=timedelta(seconds=-1)
        )
        service.add_files(store, upload, [("a.md", b"x")])
        assert service.expire_overdue(store) == 1
        assert store.get(upload.id).status == "expired"
        assert not store.files_dir(upload.id).exists()


