class TestStaging:
    def test_a_file_waits_and_is_not_in_the_twin(
        self, store: SqliteUploadStore, twin: InMemoryTwinAPI
    ) -> None:
        upload = service.stage(
            store, [("ref.png", _png(4, 3))], project_id=PROJECT, source="inline"
        )
        assert upload.status == "pending"
        (entry,) = upload.files
        assert entry.wp_type == "image" and entry.error is None
        assert store.file_path(upload.id, "ref.png").read_bytes()[:4] == b"\x89PNG"

    def test_an_unsupported_file_is_listed_with_its_reason(self, store: SqliteUploadStore) -> None:
        upload = service.stage(
            store,
            [("part.stl", b"solid x\nendsolid x\n"), ("notes.exe", b"MZ")],
            project_id=None,
            source="api",
        )
        bad = next(f for f in upload.files if f.name == "notes.exe")
        assert bad.error and "Unsupported" in bad.error
        assert [f.name for f in upload.accepted] == ["part.stl"]

    def test_nothing_importable_is_refused(self, store: SqliteUploadStore) -> None:
        with pytest.raises(service.UploadError) as exc:
            service.stage(store, [("a.exe", b"MZ")], project_id=None, source="api")
        assert exc.value.status_code == 422

    def test_a_zip_opens_into_a_folder_without_its_junk(self, store: SqliteUploadStore) -> None:
        archive = _zip(
            {
                "board.kicad_pcb": b"(kicad_pcb)",
                "src/main.c": b"int main(void){return 0;}",
                "__MACOSX/._main.c": b"junk",
                ".DS_Store": b"junk",
            }
        )
        upload = service.stage(store, [("board.zip", archive)], project_id=PROJECT, source="link")
        assert sorted(f.name for f in upload.files) == ["board/board.kicad_pcb", "board/src/main.c"]

    def test_a_zip_entry_cannot_climb_out(self, store: SqliteUploadStore) -> None:
        with pytest.raises(service.UploadError):
            service.stage(
                store, [("x.zip", _zip({"../../evil.step": b"x"}))], project_id=None, source="api"
            )

    def test_an_unknown_requested_type_is_reported(self, store: SqliteUploadStore) -> None:
        upload = service.stage(
            store,
            [("a.json", b"{}"), ("b.json", b"{}")],
            project_id=None,
            source="api",
            wp_types={"a.json": "bom", "b.json": "not_a_type"},
        )
        by_name = {f.name: f for f in upload.files}
        assert by_name["a.json"].wp_type == "bom"
        assert "Invalid wp_type" in (by_name["b.json"].error or "")


class TestDecisions:
    async def test_approval_imports_every_accepted_file(
        self, store: SqliteUploadStore, twin: InMemoryTwinAPI
    ) -> None:
        upload = service.stage(
            store,
            [("ref.png", _png(8, 6)), ("cube.gcode", GCODE)],
            project_id=PROJECT,
            source="inline",
            requested_by="local:dashboard",
        )
        done = await service.approve(store, twin, upload, approver="user:1", surface="dashboard")
        assert done.status == "approved"
        assert done.decision and done.decision.approver == "user:1"
        types = {}
        for entry in done.files:
            assert entry.work_product_id
            wp = await twin.get_work_product(UUID(entry.work_product_id))
            assert wp is not None and str(wp.project_id) == PROJECT
            assert wp.metadata["upload_id"] == upload.id
            types[entry.name] = wp.type
        assert types == {"ref.png": WorkProductType.IMAGE, "cube.gcode": WorkProductType.GCODE}
        image = await twin.get_work_product(UUID(done.files[0].work_product_id or ""))
        assert image is not None and image.metadata["width_px"] == 8
        assert not store.files_dir(upload.id).exists()

    async def test_a_decided_upload_cannot_be_decided_again(
        self, store: SqliteUploadStore, twin: InMemoryTwinAPI
    ) -> None:
        upload = service.stage(store, [("a.md", b"# a")], project_id=None, source="api")
        done = await service.approve(store, twin, upload, approver="user:1")
        with pytest.raises(service.UploadError) as exc:
            await service.approve(store, twin, done, approver="user:1")
        assert exc.value.status_code == 409

    def test_rejection_deletes_the_files_and_keeps_the_record(
        self, store: SqliteUploadStore
    ) -> None:
        upload = service.stage(store, [("a.md", b"# a")], project_id=None, source="api")
        done = service.reject(store, upload, reason="wrong part", approver="user:1")
        assert done.status == "rejected" and done.decision and done.decision.reason == "wrong part"
        assert not store.files_dir(upload.id).exists()
        assert store.get(upload.id).status == "rejected"


