class TestLinks:
    def test_a_link_verifies_and_carries_what_it_is_for(self) -> None:
        token, link = links.sign("download", "wp-1", path="a/b.png", lifetime_s=600)
        got = links.verify(token, "download")
        assert (got.kind, got.target, got.path) == ("download", "wp-1", "a/b.png")
        assert got.exp == link.exp

    def test_a_tampered_link_is_refused(self) -> None:
        token, _ = links.sign("download", "wp-1", lifetime_s=600)
        payload, mac = token.split(".")
        forged = base64.urlsafe_b64encode(b'{"k":"download","t":"wp-2","p":"","e":9999999999}')
        with pytest.raises(links.LinkError):
            links.verify(forged.decode().rstrip("=") + "." + mac)

    def test_an_expired_link_is_refused(self) -> None:
        token, _ = links.sign("download", "wp-1", lifetime_s=-5)
        with pytest.raises(links.LinkError, match="expired"):
            links.verify(token)

    def test_a_download_link_cannot_upload(self) -> None:
        token, _ = links.sign("download", "wp-1", lifetime_s=600)
        with pytest.raises(links.LinkError):
            links.verify(token, "upload")

    def test_a_link_from_another_secret_is_refused(self, monkeypatch: pytest.MonkeyPatch) -> None:
        token, _ = links.sign("download", "wp-1", lifetime_s=600)
        monkeypatch.setenv("METAFORGE_LINK_SECRET", "another-secret-" + "y" * 40)
        with pytest.raises(links.LinkError, match="not issued"):
            links.verify(token)

    def test_lifetime_grows_with_size_within_bounds(self) -> None:
        assert links.lifetime_for(0) == links.MIN_LIFETIME_S
        big = links.lifetime_for(500 * 1024 * 1024)
        assert big > links.MIN_LIFETIME_S
        assert links.lifetime_for(10**13) == links.MAX_LIFETIME_S
        assert links.lifetime_for(0, 120) == 120

    def test_the_kept_secret_survives_a_restart(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        monkeypatch.delenv("METAFORGE_LINK_SECRET")
        monkeypatch.setenv("METAFORGE_LINK_SECRET_PATH", str(tmp_path / "secret"))
        links.reset_secret_cache()
        first = links.link_secret()
        links.reset_secret_cache()
        assert links.link_secret() == first and len(first) >= 32


class TestObjectStoreLinks:
    def test_a_presigned_url_is_built_on_the_public_address(self) -> None:
        seen: dict[str, Any] = {}

        class _Client:
            def presigned_get_object(self, bucket: str, key: str, expires: timedelta) -> str:
                seen.update(bucket=bucket, key=key, expires=expires)
                return f"https://files.example.com/{bucket}/{key}?sig=x"

        settings = MinIOSettings(
            endpoint="minio:9000", access_key="a", secret_key="b", bucket="kb", secure=False
        )
        url = presign_work_product_blob(
            "work-products/1/a.step",
            timedelta(minutes=5),
            public_endpoint="https://files.example.com",
            client=_Client(),
            settings=settings,
        )
        assert url.startswith("https://files.example.com/kb/")
        assert seen["expires"] == timedelta(minutes=5)

    def test_without_a_public_endpoint_links_go_through_the_gateway(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.delenv("METAFORGE_LINK_OBJECT_STORE_ENDPOINT", raising=False)
        assert links.object_store_link("work-products/1/a.step", 600) is None


class TestReads:
    async def test_a_text_file_comes_back_as_text(self, twin: InMemoryTwinAPI) -> None:
        wp_id = await _wp(twin, "cube.gcode", GCODE)
        out = await files_service.read(twin, wp_id)
        assert out["encoding"] == "text" and out["content"].startswith("; generated")
        assert out["format"] == "gcode" and not out["truncated"]

    async def test_a_binary_file_comes_back_as_base64(self, twin: InMemoryTwinAPI) -> None:
        wp_id = await _wp(twin, "a.pdf", b"%PDF-1.4 binary\x00\x01")
        out = await files_service.read(twin, wp_id)
        assert out["encoding"] == "base64"
        assert base64.b64decode(out["content"]) == b"%PDF-1.4 binary\x00\x01"

    async def test_a_large_binary_is_refused_with_its_size(self, twin: InMemoryTwinAPI) -> None:
        wp_id = await _wp(twin, "a.pdf", b"%PDF" + b"\x00" * 5000)
        with pytest.raises(files_service.FileError) as exc:
            await files_service.read(twin, wp_id, max_bytes=100)
        assert exc.value.status_code == 413 and "5004 bytes" in str(exc.value)

    async def test_a_long_text_is_cut_and_says_so(self, twin: InMemoryTwinAPI) -> None:
        wp_id = await _wp(twin, "long.gcode", GCODE * 100)
        out = await files_service.read(twin, wp_id, max_bytes=50)
        assert out["truncated"] and len(out["content"]) == 50

    async def test_an_unknown_work_product_is_404(self, twin: InMemoryTwinAPI) -> None:
        with pytest.raises(files_service.FileError) as exc:
            await files_service.read(twin, "6f1d2c3b-0a9e-4b8c-9d7e-000000000000")
        assert exc.value.status_code == 404


