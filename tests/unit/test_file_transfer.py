class TestLocalFolder:
    async def test_a_folder_is_staged_without_its_junk(
        self, tmp_path: Path, store: SqliteUploadStore
    ) -> None:
        (tmp_path / "board").mkdir()
        (tmp_path / "board" / "board.kicad_pcb").write_text("(kicad_pcb)")
        (tmp_path / "board" / ".git").mkdir()
        (tmp_path / "board" / ".git" / "HEAD").write_text("ref")
        files = LocalFilesService(local_root=tmp_path)
        out = await files.stage_local({"paths": ["board"], "project_id": PROJECT})
        assert [f["name"] for f in out["files"]] == ["board/board.kicad_pcb"]

    async def test_nothing_outside_the_folder_is_read(self, tmp_path: Path) -> None:
        inside = tmp_path / "project"
        inside.mkdir()
        (tmp_path / "secret.txt").write_text("no")
        files = LocalFilesService(local_root=inside)
        with pytest.raises(ValueError, match="outside"):
            await files.stage_local({"paths": ["../secret.txt"]})

    async def test_save_writes_and_will_not_overwrite_unasked(
        self, tmp_path: Path, twin: InMemoryTwinAPI
    ) -> None:
        wp_id = await _wp(twin, "cube.gcode", GCODE)
        files = LocalFilesService(local_root=tmp_path)
        out = await files.save_local({"work_product_id": wp_id, "destination": "out/"})
        assert Path(out["saved_to"]).read_bytes() == GCODE
        with pytest.raises(ValueError, match="exists"):
            await files.save_local({"work_product_id": wp_id, "destination": "out/"})


