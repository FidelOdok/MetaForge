class TestUploadLinks:
    def test_a_link_takes_files_and_waits_for_a_person(
        self, client: TestClient, store: SqliteUploadStore
    ) -> None:
        made = client.post(
            "/v1/uploads/link",
            json={"project_id": PROJECT, "description": "The bracket drawings"},
        )
        assert made.status_code == 201, made.text
        path = made.json()["path"]
        page = client.get(path)
        assert page.status_code == 200 and "The bracket drawings" in page.text
        assert "script-src 'unsafe-inline'" in page.headers["content-security-policy"]
        put = client.put(f"{path}/part.step", content=STEP)
        assert put.status_code == 200, put.text
        posted = client.post(path, files=[("files", ("ref.png", b"\x89PNG\r\n\x1a\n0000"))])
        assert posted.status_code == 200
        done = client.post(f"{path}/finish").json()
        assert done["status"] == "pending" and done["accepted"] == 2
        assert store.get(made.json()["upload_id"]).source == "link"
        assert client.post(f"{path}/finish").status_code == 409

    def test_a_description_cannot_inject_html(self, client: TestClient) -> None:
        path = client.post(
            "/v1/uploads/link", json={"description": "<script>alert(1)</script>"}
        ).json()["path"]
        assert "<script>alert(1)" not in client.get(path).text

    def test_a_download_link_cannot_take_files(
        self, client: TestClient, twin: InMemoryTwinAPI
    ) -> None:
        token, _ = links.sign("download", "x", lifetime_s=60)
        assert client.put(f"/v1/links/{token}/a.step", content=STEP).status_code == 403

    def test_inline_upload_is_staged(self, client: TestClient) -> None:
        resp = client.post(
            "/v1/uploads/inline",
            json={
                "files": [
                    {"name": "notes.md", "text": "# notes"},
                    {"name": "ref.png", "content_base64": base64.b64encode(b"\x89PNG").decode()},
                ],
                "project_id": PROJECT,
            },
        )
        assert resp.status_code == 201, resp.text
        assert resp.json()["status"] == "pending" and resp.json()["source"] == "inline"

    def test_inline_upload_needs_exactly_one_content_field(self, client: TestClient) -> None:
        resp = client.post("/v1/uploads/inline", json={"files": [{"name": "a.md"}]})
        assert resp.status_code == 422


